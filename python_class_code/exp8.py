import numpy as np 
import matplotlib.pyplot as plt
# Generate random data 
np.random.seed(10) 
x = np.arange(1, 11) 
y = np.random.randint(10, 100, 10) 
# 1. Stem Plot
plt.figure() 
plt.stem(x, y) 
plt.title("Stem Plot") 
plt.xlabel("X") 
plt.ylabel("Y") 
plt.legend(["Random Data"]) 
plt.show() 
# 2. Line Plot 
plt.figure() 
plt.plot(x, y, marker='o', label="Random Data") 
plt.title("Line Plot") 
plt.xlabel("X") 
plt.ylabel("Y") 
plt.legend() 
plt.show() 
# 3. Box Plot
plt.figure() 
plt.boxplot(y) 
plt.title("Box Plot") 
plt.ylabel("Values") 
plt.legend(["Random Data"]) 
plt.show() 
# 4. Bar Plot 
plt.figure()
plt.bar(x, y, label="Random Data")
plt.title("Bar Plot") 
plt.xlabel("X") 
plt.ylabel("Y") 
plt.legend() 
plt.show() 
# 5. Scatter Plot
plt.figure() 
plt.scatter(x, y, label="Random Data") 
plt.title("Scatter Plot") 
plt.xlabel("X") 
plt.ylabel("Y") 
plt.legend() 
plt.show() 
# 6. Histogram
random_data = np.random.randn(1000) 
plt.figure()
plt.hist(random_data, bins=20, label="Random Data") 
plt.title("Histogram") 
plt.xlabel("Value") 
plt.ylabel("Frequency") 
plt.legend() 
plt.show()